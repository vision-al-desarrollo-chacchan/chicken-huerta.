create table public.huerta_admins (email text primary key check(email=lower(email)));
alter table public.huerta_admins enable row level security;
revoke all on public.huerta_admins from anon,authenticated;
grant select on public.huerta_admins to authenticated;
create policy huerta_admin_self on public.huerta_admins for select to authenticated using(email=lower((select auth.jwt()->>'email')));
create function public.is_huerta_admin() returns boolean language sql stable security invoker set search_path='' as $$
 select (select auth.uid()) is not null and exists(select 1 from public.huerta_admins where email=lower((select auth.jwt()->>'email')))
$$;
revoke all on function public.is_huerta_admin() from public;
grant execute on function public.is_huerta_admin() to authenticated;
create table public.huerta_products (
 id bigint generated by default as identity primary key,
 name text not null check(length(name) between 1 and 180),
 category text not null check(length(category) between 1 and 100),
 description text not null default '' check(length(description)<=800),
 price_cents integer not null check(price_cents between 0 and 10000000),
 image_key text check(image_key is null or image_key ~ '^products/[a-z0-9-]+\.(jpg|png|webp|gif)$'),
 available boolean not null default true,visible boolean not null default true,
 version integer not null default 1,updated_at timestamptz not null default now(),deleted_at timestamptz
);
create table public.huerta_settings(id integer primary key check(id=1),value jsonb not null,version integer not null default 1,updated_at timestamptz not null default now());
alter table public.huerta_products enable row level security;
alter table public.huerta_settings enable row level security;
revoke all on public.huerta_products,public.huerta_settings from anon,authenticated;
grant select on public.huerta_products,public.huerta_settings to anon,authenticated;
grant insert,update on public.huerta_products to authenticated;
grant update on public.huerta_settings to authenticated;
grant usage,select on sequence public.huerta_products_id_seq to authenticated;
create policy huerta_products_public on public.huerta_products for select to anon,authenticated using(visible and deleted_at is null);
create policy huerta_products_owner_read on public.huerta_products for select to authenticated using((select public.is_huerta_admin()));
create policy huerta_products_owner_insert on public.huerta_products for insert to authenticated with check((select public.is_huerta_admin()));
create policy huerta_products_owner_update on public.huerta_products for update to authenticated using((select public.is_huerta_admin())) with check((select public.is_huerta_admin()));
create policy huerta_settings_public on public.huerta_settings for select to anon,authenticated using(true);
create policy huerta_settings_owner_update on public.huerta_settings for update to authenticated using((select public.is_huerta_admin())) with check((select public.is_huerta_admin()));
create function public.huerta_bump_version() returns trigger language plpgsql security invoker set search_path='' as $$begin new.version=old.version+1;new.updated_at=now();return new;end$$;
revoke all on function public.huerta_bump_version() from public;
create trigger huerta_product_version before update on public.huerta_products for each row execute function public.huerta_bump_version();
create trigger huerta_settings_version before update on public.huerta_settings for each row execute function public.huerta_bump_version();
